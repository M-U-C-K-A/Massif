import java.io.*;
import java.lang.reflect.*;
import java.util.*;

/**
 * Prints the tables Massif's WorldPainter export writes from: the Java
 * serialisation descriptors of WorldPainter's classes (names, serial version
 * UIDs, flags, fields in stream order), the values of WorldPainter's own
 * layers, and its platforms.
 *
 * Run against WorldPainter's classes (see check.sh); the output is
 * crates/massif-legacy/src/wp_classes.rs.
 */
public class SerialSpec {
    static final Set<String> done = new LinkedHashSet<>();
    static final StringBuilder out = new StringBuilder();

    public static void main(String[] args) throws Exception {
        List<String> classes = new ArrayList<>(), layers = new ArrayList<>();
        List<String> section = classes;
        for (String line : new String(new FileInputStream(args[0]).readAllBytes()).split("\n")) {
            line = line.trim();
            if (line.equals("[layers]")) { section = layers; continue; }
            if (line.isEmpty() || line.startsWith("#")) continue;
            section.add(line);
        }
        String version = org.pepsoft.worldpainter.Version.VERSION;
        out.append("//! Tables of WorldPainter's classes for its `.world` files: their Java\n")
           .append("//! serialisation descriptors, its own layers and its platforms.\n//!\n")
           .append("//! Generated by `tools/worldpainter/SerialSpec.java` from WorldPainter ").append(version)
           .append(";\n//! do not edit by hand. WorldPainter Modernised has the same descriptors.\n\n")
           .append("use crate::javawrite::ClassSpec;\n\n")
           .append("pub const CLASSES: &[ClassSpec] = &[\n");
        for (String name : classes) emit(Class.forName(name, false, SerialSpec.class.getClassLoader()));
        out.append("];\n\n");

        out.append("/// One of WorldPainter's own layers: its class and the values of its fields.\n")
           .append("#[derive(Debug)]\npub struct LayerSpec {\n    pub class: &'static str,\n    pub id: &'static str,\n    pub name: &'static str,\n")
           .append("    pub description: &'static str,\n    pub data_size: &'static str,\n    pub priority: i32,\n    pub discrete: bool,\n}\n\n")
           .append("pub const LAYERS: &[LayerSpec] = &[\n");
        for (String name : layers) {
            Class<?> c = Class.forName(name);
            org.pepsoft.worldpainter.layers.Layer layer = (org.pepsoft.worldpainter.layers.Layer) c.getField("INSTANCE").get(null);
            Field discrete = org.pepsoft.worldpainter.layers.Layer.class.getDeclaredField("discrete");
            discrete.setAccessible(true);
            out.append("    LayerSpec { class: \"").append(name).append("\", id: ").append(lit(layer.getId()))
               .append(", name: ").append(lit(layer.getName())).append(", description: ").append(lit(layer.getDescription()))
               .append(", data_size: \"").append(layer.getDataSize().name()).append("\", priority: ").append(layer.getPriority())
               .append(", discrete: ").append(discrete.getBoolean(layer)).append(" },\n");
        }
        out.append("];\n\n");

        out.append("/// One of WorldPainter's platforms (a version of Minecraft), as its fields hold it.\n")
           .append("#[derive(Debug)]\npub struct PlatformSpec {\n    pub id: &'static str,\n    pub display_name: &'static str,\n")
           .append("    /// The int fields, by name.\n    pub ints: &'static [(&'static str, i32)],\n")
           .append("    pub max_heights: &'static [i32],\n    pub min_heights: &'static [i32],\n")
           .append("    pub game_types: &'static [&'static str],\n    pub generators: &'static [&'static str],\n")
           .append("    pub dimensions: &'static [i32],\n    pub capabilities: &'static [&'static str],\n}\n\n")
           .append("pub const PLATFORMS: &[PlatformSpec] = &[\n");
        for (Field f : org.pepsoft.worldpainter.DefaultPlugin.class.getFields()) {
            if (f.getType() != org.pepsoft.worldpainter.Platform.class) continue;
            org.pepsoft.worldpainter.Platform p = (org.pepsoft.worldpainter.Platform) f.get(null);
            out.append("    PlatformSpec { id: ").append(lit(p.id)).append(", display_name: ").append(lit(p.displayName)).append(", ints: &[");
            boolean first = true;
            for (ObjectStreamField sf : ObjectStreamClass.lookup(org.pepsoft.worldpainter.Platform.class).getFields()) {
                if (sf.getTypeCode() != 'I') continue;
                Field pf = org.pepsoft.worldpainter.Platform.class.getField(sf.getName());
                out.append(first ? "" : ", ").append("(\"").append(sf.getName()).append("\", ").append(pf.getInt(p)).append(")");
                first = false;
            }
            out.append("], max_heights: &").append(Arrays.toString(p.maxHeights)).append(", min_heights: &").append(Arrays.toString(p.minHeights));
            out.append(", game_types: &").append(names(p.supportedGameTypes)).append(", generators: &").append(names(p.supportedGenerators));
            out.append(", dimensions: &").append(p.supportedDimensions).append(", capabilities: &").append(names(p.capabilities)).append(" },\n");
        }
        out.append("];\n");
        System.out.print(out);
    }

    static String names(Collection<? extends Enum<?>> values) {
        StringBuilder sb = new StringBuilder("[");
        for (Enum<?> e : values) sb.append(sb.length() > 1 ? ", " : "").append('"').append(e.name()).append('"');
        return sb.append("]").toString();
    }

    static String lit(String s) {
        if (s == null) return "\"\"";
        return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }

    static boolean declares(Class<?> c, String name, Class<?>... params) {
        try {
            Method m = c.getDeclaredMethod(name, params);
            return Modifier.isPrivate(m.getModifiers()) && !Modifier.isStatic(m.getModifiers());
        } catch (NoSuchMethodException e) {
            return false;
        }
    }

    static void emit(Class<?> c) {
        if (c.isEnum() && c.getSuperclass() != Enum.class) c = c.getSuperclass();
        if (done.contains(c.getName())) return;
        ObjectStreamClass d = ObjectStreamClass.lookup(c);
        if (d == null) throw new IllegalArgumentException(c + " is not serializable");
        Class<?> sup = c.isArray() ? null : c.getSuperclass();
        String supName = null;
        if (sup != null && ObjectStreamClass.lookup(sup) != null) {
            emit(sup);
            supName = sup.getName();
        }
        done.add(c.getName());
        int flags = 0x02;
        if (c.isEnum() || c == Enum.class) flags |= 0x10;
        if (Externalizable.class.isAssignableFrom(c)) flags = 0x04 | 0x08;
        else if (declares(c, "writeObject", ObjectOutputStream.class)) flags |= 0x01;
        StringBuilder sb = new StringBuilder();
        sb.append("    ClassSpec { name: \"").append(c.getName()).append("\", suid: ").append(d.getSerialVersionUID())
          .append(", flags: 0x").append(String.format("%02x", flags)).append(", sup: ")
          .append(supName == null ? "None" : "Some(\"" + supName + "\")").append(", fields: &[");
        boolean first = true;
        for (ObjectStreamField f : d.getFields()) {
            sb.append(first ? "" : ", ");
            first = false;
            sb.append("(b'").append(f.getTypeCode()).append("', \"").append(f.getName()).append("\", \"")
              .append(f.isPrimitive() ? "" : f.getTypeString()).append("\")");
        }
        sb.append("], constants: &[");
        if (c.isEnum()) {
            first = true;
            for (Object k : c.getEnumConstants()) {
                sb.append(first ? "" : ", ").append("\"").append(((Enum<?>) k).name()).append("\"");
                first = false;
            }
        }
        sb.append("] },\n");
        out.append(sb);
    }
}
